// THE TABLE, AND THE SENTENCE THAT MAY INVALIDATE A DESIGN DECISION.
//
// Same honesty rule as the dispatch harness (evaluation/report.ts): the
// verdicts below are computed from the numbers, never chosen. `hedgingVerdict`
// reads the entropy correlation and prints whichever way it falls, including
// the way that says the entropy-driven hedging in src/domain/capabilitySet.ts
// is not justified by this data. Producing a flattering report would take
// deliberate effort.

import type { AiMetrics } from './metrics.js';
import type { CaseOutcome } from './metrics.js';

export type AiRow = { extractor: string; metrics: AiMetrics; outcomes: CaseOutcome[] };

function fixed(value: number, places = 3): string {
  return (value === 0 ? 0 : value).toFixed(places);
}

function percent(value: number): string {
  return `${(value * 100).toFixed(1)}%`;
}

export function metricsTable(rows: AiRow[]): string {
  const lines = [
    '| extractor | cases | predicted | top-1 | top-2 | ECE | schema valid | fallback | mean entropy | 2nd dispatch | entropy↔2nd r |',
    '| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |',
  ];

  for (const row of rows) {
    const m = row.metrics;
    lines.push(
      `| ${row.extractor} | ${m.caseCount} | ${m.predictedCount} | ${percent(m.top1Accuracy)} | ` +
        `${percent(m.top2Recall)} | ${fixed(m.expectedCalibrationError)} | ${percent(m.schemaValidRate)} | ` +
        `${percent(m.fallbackRate)} | ${fixed(m.meanEntropyBits, 2)} bits | ${percent(m.secondDispatchRate)} | ` +
        `${m.entropySecondDispatchCorrelation === null ? 'n/a' : fixed(m.entropySecondDispatchCorrelation)} |`,
    );
  }

  return lines.join('\n');
}

export function calibrationTable(row: AiRow): string {
  const lines = [
    `**Calibration — ${row.extractor}**`,
    '',
    '| confidence bin | cases | mean confidence | accuracy | gap |',
    '| --- | ---: | ---: | ---: | ---: |',
  ];

  for (const bin of row.metrics.calibrationBins) {
    if (bin.count === 0) continue;
    lines.push(
      `| ${bin.lower.toFixed(1)}–${bin.upper.toFixed(1)} | ${bin.count} | ${fixed(bin.meanConfidence)} | ` +
        `${fixed(bin.accuracy)} | ${fixed(Math.abs(bin.accuracy - bin.meanConfidence))} |`,
    );
  }

  return lines.join('\n');
}

export function languageTable(row: AiRow): string {
  const languages = ['EN', 'HI', 'MIX'];
  const lines = [
    `**By language — ${row.extractor}**`,
    '',
    '| language | cases | top-1 | top-2 |',
    '| --- | ---: | ---: | ---: |',
  ];

  for (const language of languages) {
    const inLanguage = row.outcomes.filter(
      (outcome) => outcome.language === language && outcome.predicted,
    );
    if (inLanguage.length === 0) continue;
    const top1 = inLanguage.filter((outcome) => outcome.top1 === outcome.trueFault).length;
    const top2 = inLanguage.filter((outcome) => outcome.top2.includes(outcome.trueFault)).length;
    lines.push(
      `| ${language} | ${inLanguage.length} | ${percent(top1 / inLanguage.length)} | ${percent(top2 / inLanguage.length)} |`,
    );
  }

  return lines.join('\n');
}

// THE VERDICT THE PHASE ASKED FOR, in the words the phase asked for.
export function hedgingVerdict(row: AiRow): string {
  const r = row.metrics.entropySecondDispatchCorrelation;

  if (r === null) {
    return `**${row.extractor}: not measurable.** Every scored case landed on the same second-dispatch outcome, so the correlation is undefined. The hedging policy is neither supported nor contradicted by this set — it is untested.`;
  }
  if (r <= 0) {
    return `**${row.extractor}: the hedging policy is NOT justified by this data (r = ${fixed(r)}).** Higher-entropy hypotheses were no more likely than confident ones to send a crew that could not do the work. Widening the capability set on uncertainty is currently costing option breadth for no measured benefit, and src/domain/capabilitySet.ts should be argued for on other grounds or changed.`;
  }
  if (r < 0.2) {
    return `**${row.extractor}: weak support (r = ${fixed(r)}).** The relationship points the right way but is small enough that this set cannot carry it. Treat the entropy-driven hedging as unproven rather than validated.`;
  }
  return `**${row.extractor}: supported (r = ${fixed(r)}).** Uncertain hypotheses really were the ones whose dispatched capability set failed to cover the true fault, which is the assumption the hedging in src/domain/capabilitySet.ts rests on.`;
}

export function buildReport(rows: AiRow[]): string {
  const sections = [
    '# AI intake evaluation',
    '',
    'Generated by `npm run eval:ai`. Regenerate it rather than editing it.',
    '',
    '## What this measures',
    '',
    'Free-text breakdown descriptions in English, romanised Hindi and a mixture of both, run through the real intake extraction path (`src/ai/extractSymptoms.ts`), the real rule table (`src/domain/faultRules.ts`) and the real capability set (`src/domain/capabilitySet.ts`). Labels are the fault each description was written to describe.',
    '',
    '## Results',
    '',
    metricsTable(rows),
    '',
    '## Is the entropy-driven hedging justified?',
    '',
    ...rows.map((row) => `${hedgingVerdict(row)}\n`),
    '## Calibration',
    '',
    ...rows.map((row) => `${calibrationTable(row)}\n`),
    '## Language',
    '',
    ...rows.map((row) => `${languageTable(row)}\n`),
    '## What these numbers may not be used to claim',
    '',
    '- **The labelled set is hand-written, not field data.** It was written by the same person who wrote the prompt, which is the most flattering possible arrangement. See the header of `evaluation/ai/cases.ts`.',
    '- **The second-dispatch figure is a proxy.** It is "would the capability set implied by the prediction have covered the labelled fault", computed from the label. No second callout was observed. It cannot see a technician who arrived with the right skill and the wrong part.',
    '- **`keyword-baseline` is a control, not the degraded path.** When the model is unavailable in production the driver answers the structured symptom picker; nothing dispatches on keywords.',
    '- **ECE is measured on the rule table\'s confidence, not the model\'s.** The model is never asked how sure it is — a self-reported confidence is not a calibrated one. What is calibrated here is the whole pipeline: extraction, then naive Bayes over hand-set priors.',
    '',
  ];

  return sections.join('\n');
}
