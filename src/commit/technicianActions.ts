// THE OFFLINE QUEUE'S SERVER SIDE — one technician action, applied at most
// once, in an order a flaky network cannot scramble.
//
// THE PROBLEM. A technician works in basement car parks and under flyovers.
// They tap "on my way", "arrived", "diagnosing", "working" over ten minutes
// with no signal, and the phone replays all four the moment it reconnects.
// Any of those requests can also be retried by the browser, arrive twice, or
// arrive out of order. Replaying that queue must not transition the job twice
// and must not leave it in the wrong place.
//
// TWO MECHANISMS, DELIBERATELY BOTH.
//
//   1. THE RECORD — a UNIQUE index on (job_id, idempotency_key). The phone
//      generates the key at the moment of the tap, so the same tap always
//      carries the same key however many times it is sent. The row is inserted
//      in the SAME TRANSACTION as the effect, so a duplicate raises P2002 and
//      the whole transaction — insert and effect together — rolls back. This
//      is what lets a replay be answered with the ORIGINAL outcome rather than
//      re-decided.
//
//   2. THE GUARD — a conditional UPDATE. The job only moves when its status is
//      still one of the statuses strictly BELOW the rung being claimed (see
//      domain/jobLadder.ts). This is what makes a replay harmless even when
//      the record is missed entirely: a second key for the same rung, a
//      dispatcher moving the job by another route, two of the technician's own
//      devices. It is the same shape as holds.ts and offers.ts.
//
// One of these alone would be a defensible design. Both are here because they
// answer different questions: the record answers "have I seen this tap
// before", and the guard answers "is this transition still valid at all". A
// system with only the record trusts a client-generated key to be unique
// forever; a system with only the guard cannot tell a replay from a genuine
// second attempt, and so cannot report the original outcome.
//
// WHAT IS NOT HERE. Accepting or declining an offer does not go through this
// path: an offer has a forty-five-second TTL, so it cannot meaningfully be
// answered offline, and its transition already owns a conditional update of
// its own in offers.ts. Wrapping it here would mean a second copy of that SQL.

import type { JobStatus, Prisma, PrismaClient } from '@prisma/client';
import { ladderMove, statusForStep } from '../domain/jobLadder.js';
import type { LadderStep } from '../domain/jobLadder.js';
import { appendJobEvent } from '../intake/events.js';
import { isUniqueViolation } from '../infra/prismaErrors.js';
import { ensureCompletionCode, verifyCompletionCode } from './completionCode.js';
import { runPublishingTransaction } from '../realtime/transaction.js';

export type TechnicianActionInput = {
  jobId: string;
  technicianId: string;
  // Generated by the PHONE at the moment of the tap, not by the server.
  idempotencyKey: string;
  step: LadderStep;
  // The phone's own counter. Not trusted for anything — it is recorded so the
  // order the taps actually happened in is auditable after the fact.
  clientSequence: number;
  // When the technician tapped, which during an outage is minutes before we
  // heard about it.
  eventTime: Date;
  // Required for COMPLETE and ignored otherwise.
  completionCode?: string;
};

// Every outcome is a normal answer. Only REPLAYED is about the queue itself;
// the rest are what the action meant.
export type TechnicianActionOutcome =
  | { outcome: 'APPLIED'; status: JobStatus; detail: string }
  // The job had already moved past this rung, or somebody else moved it first.
  | { outcome: 'NO_CHANGE'; detail: string }
  // This exact tap has been applied before. Carries what it decided then.
  | { outcome: 'REPLAYED'; detail: string }
  // A wrong completion code, or a job that is not on the ladder at all.
  | { outcome: 'REJECTED'; detail: string };

export async function applyTechnicianAction(
  db: PrismaClient,
  input: TechnicianActionInput,
): Promise<TechnicianActionOutcome> {
  try {
    return await runPublishingTransaction(db, (tx) => applyInsideTransaction(tx, input));
  } catch (error) {
    if (!isUniqueViolation(error)) throw error;
    // The key has been seen. Everything the transaction did has rolled back,
    // so the effect happened exactly once — at the original attempt. Answer
    // with what that attempt decided.
    return replayedOutcome(db, input);
  }
}

async function applyInsideTransaction(
  tx: Prisma.TransactionClient,
  input: TechnicianActionInput,
): Promise<TechnicianActionOutcome> {
  const job = await tx.job.findUnique({
    where: { id: input.jobId },
    select: { id: true, status: true, assignedTechnicianId: true },
  });
  if (!job) return record(tx, input, { outcome: 'REJECTED', detail: 'this job no longer exists' });

  if (job.assignedTechnicianId !== input.technicianId) {
    // They were released while offline — Phase 13's re-dispatch does exactly
    // this. Their queued actions must not move a job that is now somebody
    // else's, and they need to be told why rather than seeing a silent no-op.
    return record(tx, input, {
      outcome: 'REJECTED',
      detail: 'this job is no longer assigned to you',
    });
  }

  const move = ladderMove(job.status, input.step);
  if (move.outcome === 'OFF_LADDER') {
    return record(tx, input, { outcome: 'REJECTED', detail: 'this job is not open for work' });
  }
  if (move.outcome === 'ALREADY_PAST') {
    return record(tx, input, {
      outcome: 'NO_CHANGE',
      detail: 'this job had already moved past that step',
    });
  }

  if (input.step === 'COMPLETE') {
    const check = await verifyCompletionCode(tx, {
      jobId: input.jobId,
      code: input.completionCode ?? '',
      verifierRole: 'TECHNICIAN',
    });
    if (check.outcome === 'NO_CODE_ISSUED') {
      return record(tx, input, {
        outcome: 'REJECTED',
        detail: 'mark yourself on scene first — the driver has no code yet',
      });
    }
    if (check.outcome === 'WRONG_CODE') {
      // Recorded, not thrown. A wrong code is a real event worth keeping, and
      // the key IS claimed: an idempotency key identifies one attempt, so
      // replaying that attempt reproduces its rejection. The technician's next
      // try is a new tap and carries a new key.
      return record(tx, input, { outcome: 'REJECTED', detail: 'that code does not match' });
    }
  }

  // THE GUARD. Named statuses rather than a version number, because the ladder
  // is the thing being guarded: any status below this rung is a legal place to
  // move from, and every other writer in the system moves the job somewhere
  // this WHERE clause does not list.
  const moved = await tx.job.updateMany({
    where: { id: input.jobId, status: { in: move.from } },
    data: { status: move.to, version: { increment: 1 }, ...resolvedAtFor(input.step) },
  });
  if (moved.count === 0) {
    return record(tx, input, {
      outcome: 'NO_CHANGE',
      detail: 'somebody else moved this job first',
    });
  }

  // The driver's code exists from the moment the technician is on scene, so by
  // the time it is asked for it has been on the driver's phone all along.
  if (input.step === 'ARRIVED') await ensureCompletionCode(tx, input.jobId);

  await appendJobEvent(tx, {
    jobId: input.jobId,
    eventType: EVENT_FOR_STEP[input.step],
    payload: { idempotencyKey: input.idempotencyKey, clientSequence: input.clientSequence },
    actorRole: 'TECHNICIAN',
    actorId: input.technicianId,
    at: input.eventTime,
  });

  return record(tx, input, {
    outcome: 'APPLIED',
    status: statusForStep(input.step),
    detail: 'recorded',
  });
}

const EVENT_FOR_STEP: Record<LadderStep, string> = {
  EN_ROUTE: 'TECHNICIAN_EN_ROUTE',
  ARRIVED: 'TECHNICIAN_ARRIVED',
  DIAGNOSING: 'TECHNICIAN_DIAGNOSING',
  WORKING: 'TECHNICIAN_WORKING',
  COMPLETE: 'JOB_COMPLETION_VERIFIED',
};

function resolvedAtFor(step: LadderStep): { resolvedAt?: Date } {
  return step === 'COMPLETE' ? { resolvedAt: new Date() } : {};
}

// The insert that claims the key. LAST in the transaction, so a duplicate
// aborts a transaction whose effect is already staged and takes the effect
// down with it — which is the whole guarantee.
async function record(
  tx: Prisma.TransactionClient,
  input: TechnicianActionInput,
  outcome: TechnicianActionOutcome,
): Promise<TechnicianActionOutcome> {
  await tx.technicianAction.create({
    data: {
      jobId: input.jobId,
      technicianId: input.technicianId,
      idempotencyKey: input.idempotencyKey,
      kind: input.step,
      clientSequence: input.clientSequence,
      outcome: outcome.outcome,
      detail: outcome.detail,
      eventTime: input.eventTime,
    },
  });
  return outcome;
}

async function replayedOutcome(
  db: PrismaClient,
  input: TechnicianActionInput,
): Promise<TechnicianActionOutcome> {
  const original = await db.technicianAction.findUnique({
    where: { jobId_idempotencyKey: { jobId: input.jobId, idempotencyKey: input.idempotencyKey } },
    select: { outcome: true, detail: true },
  });
  return {
    outcome: 'REPLAYED',
    detail: original ? `already applied: ${original.detail ?? original.outcome}` : 'already applied',
  };
}
